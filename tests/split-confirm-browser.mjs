import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({executablePath:'/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',headless:true});
const page=await browser.newPage({viewport:{width:1360,height:900}});page.setDefaultTimeout(15000);
try {
 await page.goto('http://localhost:1437/__split-confirm');
 const review=page.getByRole('region',{name:'候选分章方案'});
 const rules=review.getByRole('button',{name:'分章规则',exact:true});
 const adopt=review.getByRole('button',{name:'采用整套方案'});
 await adopt.waitFor();
 const adoptNode=await adopt.elementHandle();
 const adoptTop=await adopt.evaluate(el=>el.getBoundingClientRect().top);
 await rules.click();
 await page.getByRole('dialog',{name:'分章规则'}).waitFor();
 assert.equal(await adoptNode.evaluate(el=>el.getBoundingClientRect().top),adoptTop);
 await page.keyboard.press('Escape');
 await page.getByRole('dialog',{name:'分章规则'}).waitFor({state:'hidden'});
 assert.equal(await rules.evaluate(el=>el===document.activeElement),true);
 assert.equal(await page.evaluate(()=>window.fixture.calls.length),0);
 const changes=review.getByRole('checkbox',{name:'仅看变化'});
 assert.equal(await changes.isChecked(),true); await changes.uncheck(); await changes.check();
 await review.getByRole('button',{name:'采用整套方案'}).click();
 let dialog=page.getByRole('dialog',{name:'确认采用分章方案'}); await dialog.waitFor();
 await page.waitForFunction(el=>el===document.activeElement,await dialog.getByRole('button',{name:'取消'}).elementHandle());
 const text=await dialog.innerText();
 assert.match(text,/工程：山海之间/); assert.match(text,/第二章 来客/); assert.match(text,/山海之间.txt.*第 11 行/); assert.match(text,/历史音频会保留/);
 await dialog.getByRole('button',{name:'取消'}).click(); await dialog.waitFor({state:'hidden'});
 assert.equal(await page.evaluate(()=>window.fixture.calls.length),0);
 await review.getByRole('button',{name:'采用整套方案'}).click();
 dialog=page.getByRole('dialog',{name:'确认采用分章方案'});
 await page.evaluate(()=>{window.fixture.failAdopt=true;});
 await dialog.getByRole('button',{name:'确认采用'}).click();
 await dialog.waitFor({state:'hidden'});
 await review.getByText('结构操作结果尚未确认，原请求已保留。').waitFor();
 assert.equal(await review.getByRole('button',{name:'放弃方案'}).isDisabled(),true);
 await page.evaluate(()=>{window.fixture.failAdopt=false;});
 await review.getByRole('button',{name:'重试原操作'}).click();
 await review.getByText('已采用').waitFor();
 const calls=await page.evaluate(()=>window.fixture.calls);
 assert.equal(calls.length,2); assert.equal(calls[0].commandId,calls[1].commandId);
 console.log('PASS proposal context, safe focus, cancellation and same-operation retry');
} finally { await browser.close(); }
