import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
const errors = [];
try {
 for (const locale of ["zh", "en"]) for (const theme of ["light", "dark"]) for (const width of [1440, 1024]) {
  const p = await browser.newPage({ viewport: { width, height: 780 } });
  p.on("pageerror", e => errors.push(e.message));
  p.setDefaultTimeout(10000);
  await p.goto(`http://localhost:1437/new?draft=fixture-project&fixture=desktop&largeDirectory=1&grouped=1&locale=${locale}&theme=${theme}`);
  const zh = locale === "zh";
  await p.locator('[data-slot="source-toolbar"]').waitFor();
  const tree = p.getByRole("tree");
  if (!await tree.isVisible()) await p.locator('[data-slot="desktop-bar"]').getByRole("button", { name: zh ? "目录" : "Directory", exact: true }).click();
  await tree.waitFor();
  const search = p.getByRole("searchbox", { name: zh ? "搜索章节或目录序号" : "Search chapters or directory position", exact: true });
  const readCount = () => p.evaluate(() => window.fixture.calls.filter(c => c.command === "local_project_text").length);
  await p.locator('[data-slot="source-scroll"][aria-busy="false"]').waitFor();
  const before = await readCount();
  await search.fill("2200");
  await tree.getByRole("treeitem").last().waitFor();
  assert.equal(await readCount(), before, "filtering never reads source");
  await search.press("Enter");
  await p.waitForFunction(() => window.fixture.calls.some(c => c.command === "local_project_text" && c.args.line >= 21988));
  await search.fill("not-a-chapter");
  await p.getByText(zh ? "没有匹配的章节" : "No matching chapters", { exact: true }).waitFor();
  await search.press("Escape");
  assert.equal(await search.inputValue(), "");
  const toolbar = p.locator('[data-slot="source-toolbar"]');
  const header = p.locator('[data-slot="directory-toolbar"]');
  assert.equal((await header.boundingBox()).height, 56);
  assert.equal(await header.evaluate(el => el.scrollWidth > el.clientWidth), false);
  assert.equal(await tree.evaluate(el => el.getBoundingClientRect().width >= 280), true);
  const tab = p.getByRole("tab", {name:zh ? "待检查" : "Needs review",exact:true});
  const treeTop = await tree.evaluate(el => el.getBoundingClientRect().top);
  await tab.click();
  assert.equal(await p.getByRole("region",{name:zh ? "分章待检查" : "Chapter issues",exact:true}).evaluate(el => el.getBoundingClientRect().top), treeTop);
  await p.getByRole("tab",{name:zh ? "目录" : "Directory",exact:true}).click();
  const directoryTab = p.getByRole("tab", {name:zh ? "目录" : "Directory",exact:true});
  await directoryTab.hover();
  const hint = p.locator('[data-slot="tooltip-content"]').filter({hasText:"2335"});
  await hint.waitFor();
  assert.equal(await hint.getAttribute("data-side"), "bottom");
  assert.ok((await hint.boundingBox()).y >= (await header.boundingBox()).y + 32);
  await p.mouse.move(600, 300);
  await hint.waitFor({state:"hidden"});
  const box = await toolbar.boundingBox();
  assert.equal(box.height, 56);
  const information=toolbar.getByRole("button",{name:zh?"原文信息":"Source information",exact:true});
  await information.hover();
  const sourceTip=p.locator('[data-slot="tooltip-content"]').filter({hasText:zh?/目录位置 2200\/2335/:/Directory position 2200\/2335/});
  await sourceTip.waitFor();
  assert.equal(await sourceTip.getAttribute("data-side"),"bottom");
  assert.ok((await sourceTip.locator('[data-slot="source-info-details"] p').first().innerText()).endsWith('.txt'));
  await p.mouse.move(800,300);await sourceTip.waitFor({state:"hidden"});
  await information.focus();
  await p.keyboard.press("Tab"); await p.keyboard.press("Shift+Tab");
  await sourceTip.waitFor();
  await information.press("Enter");
  const infoPanel=p.locator('[data-slot="popover-content"]');
  await infoPanel.waitFor();
  assert.equal(await infoPanel.getByRole("combobox").count(),0);
  await p.keyboard.press("Escape");await infoPanel.waitFor({state:"hidden"});
  assert.equal(await information.evaluate(el=>el===document.activeElement),true);
  assert.equal(await toolbar.locator('[data-slot="source-info-details"]').count(),0);
  const display = p.getByRole("button", { name: zh ? "紧凑校对" : "Compact proofreading", exact: true });
  assert.equal(await display.getAttribute("aria-pressed"), "true");
  const buttonBox=await display.boundingBox();
  assert.equal(buttonBox.width,32);
  assert.equal(buttonBox.height,32);
  assert.equal(await display.locator('svg').count(),1);
  assert.equal(await display.locator('[data-slot="source-display-compact"]').count(),1);
  await display.click();
  assert.equal(await display.getAttribute("aria-pressed"), "false");
  assert.equal(await display.locator('svg').count(),1);
  assert.equal(await display.locator('[data-slot="source-display-original"]').count(),1);
  assert.deepEqual(await display.boundingBox(),buttonBox);
  assert.equal(await toolbar.getByRole("combobox").count(),0);
  await display.focus(); await display.press("Space");
  assert.equal(await display.getAttribute("aria-pressed"), "true");
  await p.mouse.move(800,300);
  await display.hover();
  const toggleTip=p.locator('[data-slot="tooltip-content"]').filter({hasText:zh?'当前紧凑校对':'Compact proofreading is on'});
  await toggleTip.waitFor();
  assert.equal(await toggleTip.getAttribute("data-side"),"bottom");
  await p.mouse.move(800,300);await display.blur();
  await toggleTip.waitFor({state:"hidden"});
  assert.deepEqual(await toolbar.boundingBox(), box);
  const go = p.getByRole("button", { name: zh ? "转到行" : "Go to line", exact: true });
  await go.click();
  const line = p.getByRole("spinbutton", { name: zh ? "转到行" : "Go to line", exact: true });
  await p.waitForFunction(el => el === document.activeElement, await line.elementHandle());
  await line.fill("0");
  // Invalid input stays in the popup and displays an inline error.
  await line.press("Enter");
  assert.equal(await line.isVisible(), true);
  await p.getByRole("alert").waitFor();
  await line.fill("12"); await line.press("Enter");
  await p.locator('[data-source-line="11"]').waitFor();
  await p.locator('[data-slot="popover-content"]').waitFor({state:"hidden"});
  await p.keyboard.press("Control+g"); await line.waitFor();
  assert.equal(await line.inputValue(), "12");
  await p.keyboard.press("Escape");
  await p.locator('[data-slot="popover-content"]').waitFor({ state: "hidden" });
  assert.equal(await go.evaluate(el => el === document.activeElement), true);
  await p.getByRole("button", { name: zh ? "分卷设置" : "Volume settings", exact: true }).click();
  await p.locator('[data-slot="dialog-content"]').waitFor();
  assert.deepEqual(await toolbar.boundingBox(), box);
  await p.keyboard.press("Escape");
  await p.locator('[data-slot="popover-content"]').waitFor({ state: "hidden" });
  await p.locator('[data-slot="dialog-content"]').waitFor({state:"hidden"});
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await toolbar.evaluate(el => el.scrollWidth > el.clientWidth), false);
  await p.screenshot({ path: `src-tauri/target/workbench-acceptance/reading-toolbar-${locale}-${theme}-${width}.png`, animations: "disabled" });
  assert.deepEqual(await p.evaluate(() => window.fixture.unexpected), []);
  await p.close();
 }
 assert.deepEqual(errors, []);
 console.log("PASS 8 actual-route layouts: unified navigation, no read on typing, source/position semantics, display/jump/volume overlays, keyboard/focus, fixed geometry and no overflow");
} finally { await browser.close(); }
