import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
page.setDefaultTimeout(20000);
try {
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1");
  await page.getByRole("button", { name: "返回 AI 助手", exact: true }).click();
  await page.getByRole("button", { name: "检查分章", exact: true }).click();
  await page.getByRole("button", { name: "查看分章方案", exact: true }).click();
  const proposal = page.getByRole("dialog", { name: "分章方案", exact: true });
  await proposal.getByRole("button", { name: "采用整套方案" }).click();
  await page.evaluate(() => { window.fixture.loseSplitReply = true; });
  await page.getByRole("dialog", { name: "确认采用分章方案" }).getByRole("button", { name: "确认采用" }).click();
  await proposal.getByText("结构操作结果尚未确认，原请求已保留。").waitFor();
  assert.equal(await proposal.getByRole("button", { name: "放弃方案" }).isDisabled(), true);
  assert.equal(await page.evaluate(() => window.fixture.splitWrites), 1);
  await page.keyboard.press("Escape");
  await proposal.waitFor({ state: "hidden" });
  await page.getByRole("link", { name: "工程首页", exact: true }).click();
  await page.goBack();
  await page.getByText("结构操作结果尚未确认，原请求已保留。").waitFor();
  await page.getByRole("button", { name: "重试原操作" }).click();
  await page.getByText("结构操作结果尚未确认，原请求已保留。").waitFor({ state: "hidden" });
  assert.equal(await page.evaluate(() => window.fixture.splitWrites), 1);
  const calls = await page.evaluate(() => window.fixture.calls.filter(call => call.command === "split_adopt").map(call => call.args));
  assert.equal(calls.length, 2);
  assert.deepEqual(calls[0], calls[1]);
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(call => call.command === "split_discard").length), 0);
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1");
  await page.getByRole("button", { name: "返回 AI 助手", exact: true }).click();
  await page.getByRole("button", { name: "检查分章", exact: true }).click();
  await page.getByRole("button", { name: "查看分章方案", exact: true }).click();
  const second = page.getByRole("dialog", { name: "分章方案", exact: true });
  await second.getByRole("button", { name: "放弃方案" }).waitFor();
  await page.evaluate(() => { window.fixture.failSnapshot = true; });
  await second.getByRole("button", { name: "放弃方案" }).click();
  await second.getByText("结构操作已确认，但目录读取失败。").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.splitWrites), 1);
  await page.evaluate(() => { window.fixture.failSnapshot = false; });
  await second.getByRole("button", { name: "重新读取目录" }).click();
  await second.getByText("已放弃").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(call => call.command === "split_discard").length), 1);
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1");
  await page.getByRole("button", { name: "返回 AI 助手", exact: true }).click();
  await page.getByRole("button", { name: "检查分章", exact: true }).click();
  await page.getByRole("button", { name: "查看分章方案", exact: true }).click();
  const third = page.getByRole("dialog", { name: "分章方案", exact: true });
  await third.getByRole("button", { name: "采用整套方案" }).click();
  await page.evaluate(() => { window.fixture.delaySplit = true; });
  await page.getByRole("dialog", { name: "确认采用分章方案" }).getByRole("button", { name: "确认采用" }).click();
  await page.waitForFunction(() => typeof window.fixture.releaseSplit === "function");
  await page.keyboard.press("Escape");
  await third.waitFor({ state: "hidden" });
  await page.getByRole("link", { name: "工程首页", exact: true }).click();
  await page.goBack();
  await page.getByText("正在核对结构操作…").waitFor();
  await page.evaluate(() => window.fixture.releaseSplit());
  await page.getByText("正在核对结构操作…").waitFor({ state: "hidden" });
  assert.equal(await page.evaluate(() => window.fixture.splitWrites), 1);
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(call => call.command === "split_adopt").length), 1);
  console.log("PASS proposal recovery retains original identity across route changes");
} finally { await browser.close(); }
