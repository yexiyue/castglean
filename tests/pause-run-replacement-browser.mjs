import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
const page = await browser.newPage();
page.setDefaultTimeout(30000);
try {
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&audio=1&windowFixture=1");
  await page.getByRole("button", { name: "分析本章", exact: true }).click();
  await page.locator("[data-segment-id]").first().waitFor();
  await page.getByRole("button", { name: "生成本章音频", exact: true }).click();
  const track = page.getByRole("region", { name: "章节音频轨道" });
  await track.locator('[data-unit-index="0"]').click();
  await track.getByRole("button", { name: "添加停顿", exact: true }).click();
  await page.waitForFunction(() => window.fixture.audio.arrangement.revision === 1);
  const input = page.getByRole("spinbutton", { name: "额外停顿（秒）" });
  await page.waitForFunction(() => !document.querySelector('input[role="spinbutton"]')?.disabled);
  await page.evaluate(() => { window.fixture.losePauseReply = true; });
  await input.fill("0.75");
  await input.press("Tab");
  await page.getByRole("button", { name: "重试停顿操作" }).waitFor();
  await page.evaluate(async () => await window.fixture.fireWindowClose());
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "confirm_window_close").length), 0);
  await page.getByRole("button", { name: "关闭工程标签：山海之间" }).click();
  assert.match(page.url(), /\/project\/fixture-project/);
  const original = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_arrangement_edit").at(-1).args);
  await page.evaluate(() => { window.fixture.emptyAudioStatus = true; window.fixture.audio.run.status = "succeeded"; });
  await page.locator('[data-slot="chapter-audio-track"]').waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "重试停顿操作" }).waitFor();
  const generate = page.getByRole("button", { name: "生成本章音频", exact: true });
  await page.waitForFunction(() => { const button = document.querySelector('button[aria-label="生成本章音频"]'); return button && !button.disabled; });
  const starts = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_start").length);
  await generate.click();
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_start").length), starts);
  await page.evaluate(() => {
    const state = window.fixture.audio;
    window.fixture.emptyAudioStatus = false;
    state.run.id = "replacement-run";
    state.run.chapterTitle = "新音频版本";
    state.run.revision++;
    state.arrangement = { runId: "replacement-run", revision: 0, pauses: [], canUndo: false, stale: false };
  });
  await page.locator('[data-slot="chapter-audio-track"][data-run-id="replacement-run"]').waitFor();
  await page.getByText("“山雨”的停顿修改结果尚未确认，请重试原操作。", { exact: true }).waitFor();
  await page.getByRole("button", { name: "重试停顿操作" }).click();
  await page.getByText("“山雨”之前的停顿修改已确认。", { exact: true }).waitFor();
  const calls = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_arrangement_edit").slice(-2).map(c => c.args));
  assert.deepEqual(calls[1], original);
  assert.deepEqual(await page.evaluate(() => window.fixture.audio.arrangement.pauses), []);
  assert.equal(await page.getByRole("button", { name: "重试停顿操作" }).count(), 0);
  console.log("PASS lost pause receipt survives replacement run and replays original operation");
} finally { await browser.close(); }
