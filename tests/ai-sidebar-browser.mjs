// Run against tests/helpers/serve-workbench.mjs; only synthetic IPC and text.
import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
const page = await browser.newPage({ viewport: { width: 1024, height: 680 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const input = page.getByRole("textbox", { name: "分章问题或补充说明" });
const inputText = () => input.inputValue();
const paste = text => page.keyboard.insertText(text);
try {
  await page.goto("http://localhost:1437/__workbench?markdown=1");
  await input.waitFor();
  assert.equal(await input.evaluate(element => element.tagName), "TEXTAREA");
  await page.getByRole("log").locator('[data-streamdown="strong"]').waitFor();
  assert.equal(await page.getByRole("log").locator("table").count(), 1);
  assert.ok((await page.getByRole("log").locator("code").innerText()).includes("^第"));
  await input.fill("<tag>字面标签🙂</tag>");
  assert.equal(await input.locator("tag").count(), 0);
  assert.equal(await inputText(), "<tag>字面标签🙂</tag>");
  await input.press("End"); await input.press("Enter"); await input.press("Shift+Enter");
  await paste("第一行\n第二行🙂");
  const expected = "<tag>字面标签🙂</tag>\n\n第一行\n第二行🙂";
  assert.equal(await inputText(), expected);
  await input.fill("中".repeat(2000));
  await input.press("End"); await input.press("x");
  assert.equal((await inputText()).length, 2001);
  await paste("🙂".repeat(5000));
  assert.ok((await inputText()).length > 10000);
  await input.fill(expected);
  await page.getByRole("button", { name: "新建诊断", exact: true }).click();
  assert.equal(await inputText(), "");
  await page.getByRole("button", { name: "诊断历史", exact: true }).click();
  await page.getByRole("button", { name: /检查遗漏的章节标题/ }).click();
  assert.equal(await inputText(), expected);
  await input.press("Control+Enter");
  await page.waitForFunction(() => window.fixture.calls.some(call => call.command === "ai_start"));
  assert.equal(await page.evaluate(() => window.fixture.calls.find(call => call.command === "ai_start").args.request.trigger.message), expected);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: "src-tauri/target/workbench-acceptance/ai-sidebar-prompt-input.png" });

  await page.goto("http://localhost:1437/__workbench?status=running&markdown=1&theme=dark");
  await page.getByRole("button", { name: "停止", exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "停止", exact: true }).isDisabled(), false);
  await page.evaluate(() => window.fixture.streamText("## 流式检查\n\n- **正在读取**\n\n```rust\nfn check() {"));
  await page.getByRole("log").locator("code").filter({ hasText: "fn check" }).waitFor();
  await page.evaluate(() => window.fixture.streamText("## 流式检查\n\n- **读取完成**\n\n```rust\nfn check() {}\n```\n\n| 章节 | 状态 |\n| --- | --- |\n| 第二章 | 建议新增 |"));
  await page.getByRole("log").locator("table").waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: "src-tauri/target/workbench-acceptance/ai-sidebar-streamdown-dark.png" });
  assert.deepEqual(errors, []);
  console.log("PASS: shadcn Prompt Input literal text/multiline/paste/long text/draft restore/plain-text send; AI Elements Markdown/table/CJK/code/incomplete stream, 1024px, no browser errors.");
} catch (error) { console.error("Browser errors:", errors); console.error((await page.locator("body").innerText()).slice(-2000)); await page.screenshot({ path: "src-tauri/target/workbench-acceptance/ai-sidebar-failure.png" }); throw error; } finally { await browser.close(); }
