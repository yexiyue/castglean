import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
const page = await browser.newPage({ viewport: { width: 1024, height: 680 } });
const errors = []; page.on("pageerror", error => errors.push(error.message)); page.setDefaultTimeout(15000);
try {
 await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1");
 await page.getByRole("button", { name: "返回 AI 助手", exact: true }).click();
 const input = page.getByRole("textbox", { name: "工程问题或补充说明" });
 assert.equal(await input.evaluate(el => el.tagName), "TEXTAREA");
 assert.deepEqual(await input.evaluate(el => { const style = getComputedStyle(el); return [style.paddingLeft, style.lineHeight]; }), ["12px", "24px"]);
 await input.fill("创建公开会话"); await page.getByRole("button", { name: "发送", exact: true }).click();
 await page.waitForFunction(() => window.fixture.calls.some(c => c.command === "ai_start"));
 const log = page.getByRole("log");
 const logNode = await log.elementHandle();
 const logTop = await log.evaluate(el => el.getBoundingClientRect().top);
 const history = page.getByRole("button", { name: "会话历史", exact: true });
 await history.click(); await page.getByRole("dialog", { name: "会话历史" }).waitFor();
 assert.equal(await logNode.evaluate(el => el.getBoundingClientRect().top), logTop);
 await page.keyboard.press("Escape"); await page.getByRole("dialog", { name: "会话历史" }).waitFor({ state: "hidden" });
 await page.waitForFunction(el => el === document.activeElement, await history.elementHandle());
 assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "ai_start").length), 1);
 await input.fill("<tag>字面标签🙂</tag>");
 assert.equal(await input.locator("tag").count(), 0);
 await input.press("End"); await input.press("Enter"); await input.press("Shift+Enter");
 await page.keyboard.insertText("第一行\n第二行🙂");
 const expected = "<tag>字面标签🙂</tag>\n\n第一行\n第二行🙂";
 assert.equal(await input.inputValue(), expected);
 await input.press("End"); await page.keyboard.insertText("undo-me");
 await input.press(process.platform === "darwin" ? "Meta+z" : "Control+z");
 assert.equal(await input.inputValue(), expected);
 await input.fill("中".repeat(2000)); await input.press("End"); await input.press("x");
 assert.equal((await input.inputValue()).length, 2001);
 await page.keyboard.insertText("🙂".repeat(5000)); assert.ok((await input.inputValue()).length > 10000);
 await input.fill(expected);
 await page.getByRole("button", { name: "新建会话", exact: true }).click();
 await page.waitForFunction(() => document.querySelector('[aria-label="工程问题或补充说明"]')?.value === "");
 await page.getByRole("button", { name: "会话历史", exact: true }).click();
 await page.getByRole("dialog", { name: "会话历史" }).getByRole("button", { name: "创建公开会话" }).click();
 assert.equal(await input.inputValue(), expected);
 await input.press(process.platform === "darwin" ? "Meta+Enter" : "Control+Enter");
 await page.waitForFunction(() => window.fixture.calls.filter(c => c.command === "ai_start").length === 2);
 assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "ai_start").at(-1).args.request.trigger.message), expected);
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
 assert.deepEqual(await page.evaluate(() => window.fixture.unexpected), []);
 assert.deepEqual(errors, []);
 console.log("PASS actual assistant input: literal text, multiline, undo, long input, session drafts and send");
} finally { await browser.close(); }
