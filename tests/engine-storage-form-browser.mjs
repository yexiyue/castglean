import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1024, height: 680 } });
  const url = new URL("http://localhost:1437/project/fixture-project?fixture=desktop&storageFixture=1");
  url.searchParams.set("storageCredential", "1");
  url.searchParams.set("settings", "storage");
  url.searchParams.set("windowFixture", "1");
  await page.goto(url.href);
  const dialog = page.getByRole("dialog", { name: "设置" });
  const endpoint = dialog.getByRole("textbox", { name: "下载源端点" });
  const token = dialog.getByLabel("访问凭据（可选）");
  const save = dialog.getByRole("button", { name: "保存设置" });
  const remove = dialog.getByRole("checkbox", { name: "移除现有下载凭据" });
  await remove.waitFor();
  assert.equal(await token.inputValue(), "");
  assert.equal(await token.getAttribute("placeholder"), "留空以保留现有凭据");
  await endpoint.fill("https://user:example@example.com");
  await save.click();
  await dialog.getByText("请输入不含内嵌凭据的有效 HTTP 或 HTTPS 地址。").waitFor();
  assert.equal(await endpoint.evaluate(el => el === document.activeElement), true);
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "update_engine_settings").length), 0);
  await endpoint.fill("https://mirror.example.com");
  await dialog.getByRole("button", { name: "选择应用数据目录" }).click();
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "update_engine_settings").length), 0);
  await dialog.getByRole("button", { name: "恢复默认应用数据目录" }).click();
  await save.click();
  await dialog.getByText("已保存。", { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "update_engine_settings").at(-1).args.settings.download_token), {kind:"keep"});
  await token.fill("synthetic-replacement");
  await dialog.getByRole("button", { name: "通用", exact: true }).click();
  await dialog.getByRole("button", { name: "存储位置", exact: true }).click();
  assert.equal(await token.inputValue(), "synthetic-replacement");
  assert.equal(await page.evaluate(() => {
    const event = new Event("beforeunload", { cancelable: true });
    window.dispatchEvent(event);
    return event.defaultPrevented;
  }), true);
  await dialog.getByRole("button", { name: "关闭", exact: true }).click();
  await page.waitForFunction(() => typeof window.fixture.fireWindowClose === "function");
  await page.evaluate(() => window.fixture.fireWindowClose());
  const close = page.getByRole("alertdialog", { name: "关闭 CastGlean？" });
  await close.getByText("设置草稿或保存结果尚未确认；关闭后草稿、密钥输入及原请求身份会丢失。").waitFor();
  await close.getByRole("button", { name: "继续使用" }).click();
  await page.getByRole("button", { name: "设置", exact: true }).first().click();
  await dialog.getByRole("button", { name: "存储位置", exact: true }).click();
  assert.equal(await token.inputValue(), "synthetic-replacement");
  await dialog.getByRole("button", { name: "放弃修改" }).click();
  assert.equal(await token.inputValue(), "");
  assert.equal(await page.evaluate(() => {
    const event = new Event("beforeunload", { cancelable: true });
    window.dispatchEvent(event);
    return event.defaultPrevented;
  }), false);
  assert.equal(await save.isDisabled(), true);
  await token.fill("synthetic-replacement");
  await save.click();
  await page.waitForFunction(() => window.fixture.calls.filter(c => c.command === "update_engine_settings").length === 2);
  assert.deepEqual(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "update_engine_settings").at(-1).args.settings.download_token), {kind:"replace",value:"synthetic-replacement"});
  await page.waitForFunction(() => document.querySelector('#engine-download-token')?.value === "");
  await remove.check();
  assert.equal(await token.isDisabled(), true);
  await save.click();
  await page.waitForFunction(() => window.fixture.calls.filter(c => c.command === "update_engine_settings").length === 3);
  assert.deepEqual(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "update_engine_settings").at(-1).args.settings.download_token), {kind:"remove"});
  await remove.waitFor({state:"hidden"});
  assert.equal(await token.inputValue(), "");
  await endpoint.fill("https://first.example.org");
  await page.evaluate(() => { window.fixture.loseEngineReply = true; });
  await save.click();
  await dialog.getByText("保存结果尚未确认。重试使用原请求；停止核对不会撤销可能已完成的保存。").waitFor();
  assert.equal(await endpoint.isDisabled(), true);
  await page.evaluate(() => { window.fixture.failEngineRead = true; });
  await dialog.getByRole("button", { name: "重新读取设置" }).click();
  await dialog.getByText("设置读取失败，请重试。").waitFor();
  assert.equal(await dialog.getByRole("button", { name: "停止核对并继续编辑" }).isDisabled(), true);
  await page.evaluate(() => { window.fixture.failEngineRead = false; window.fixture.changeEngineEndpoint("https://later.example.org"); });
  await dialog.getByRole("button", { name: "重新读取设置" }).click();
  await dialog.getByText("已重新读取设置，但无法确认凭据内容或本次保存是否完成。").waitFor();
  await dialog.getByRole("button", { name: "重试原保存" }).click();
  await dialog.getByText("已保存。", { exact: true }).waitFor();
  assert.equal(await endpoint.inputValue(), "https://later.example.org");
  assert.equal(await page.evaluate(() => window.fixture.engineWrites), 4);
  const calls = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "update_engine_settings"));
  assert.equal(calls.at(-1).args.operationId, calls.at(-2).args.operationId);
  await endpoint.fill("https://draft.example.org");
  await token.fill("synthetic-draft");
  await page.evaluate(() => window.fixture.changeEngineEndpoint("https://external.example.org"));
  await save.click();
  await dialog.getByText("设置已变化，请重新读取并核对草稿后再保存。").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.engineWrites), 4);
  await dialog.getByRole("button", { name: "重新读取设置" }).click();
  await dialog.getByRole("button", { name: "停止核对并继续编辑" }).click();
  assert.equal(await endpoint.inputValue(), "https://draft.example.org");
  assert.equal(await token.inputValue(), "synthetic-draft");
  await dialog.getByRole("button", { name: "放弃修改" }).click();
  assert.equal(await endpoint.inputValue(), "https://external.example.org");
  assert.equal(await token.inputValue(), "");
  console.log("PASS credentials, drafts and recovery without replaying a later edit");
} finally { await browser.close(); }
