//! 强制导出 TypeScript bindings 的测试。
//!
//! `cargo build` 不会触发 `lib.rs` debug 分支里的 export（应用没起来），
//! 把 export 抽到这里，`cargo test` 即可刷新 `src/lib/bindings.ts`，
//! CI 借此校验 bindings 与命令注册保持同步：
//!
//! ```bash
//! cargo test --test specta_export -- --nocapture
//! ```

#[test]
fn export_bindings() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/bindings.ts");
    castglean_lib::specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// AUTO-GENERATED by tauri-specta. DO NOT EDIT.\n"),
            path,
        )
        .expect("export TS bindings");
    // Normalize exporter whitespace as part of generation, never by editing the generated file.
    let exported = std::fs::read_to_string(path).expect("read generated bindings");
    let canonical = exported
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    std::fs::write(path, canonical).expect("write generated bindings");
}
