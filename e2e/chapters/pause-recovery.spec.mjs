import assert from 'node:assert/strict';
import { test } from "../managed-browser.mjs";

test("pause-recovery", async ({ flowBrowser: browser }) => {
const page = await browser.newPage(); page.setDefaultTimeout(60000);
try {
 await page.goto('http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&audio=1&windowFixture=1');
 await page.getByRole('button',{name:'分析本章',exact:true}).click();
 await page.locator('[data-segment-id]').first().waitFor();
 await page.getByRole('button',{name:'生成本章音频',exact:true}).click();
 const track=page.getByRole('region',{name:'章节音频轨道'});
 await track.locator('[data-unit-index="0"]').click();
 await track.getByRole('button',{name:'添加停顿',exact:true}).click();
 const boundary=page.getByLabel('移动到片段之后',{exact:true}); await boundary.waitFor();
 await page.waitForFunction(()=>window.fixture.audio.arrangement.revision===1 && !document.querySelector('select[id$="-boundary"]')?.disabled);
 assert.equal(await boundary.inputValue(),'0');
 await page.evaluate(()=>{window.fixture.losePauseReply=true;});
 await boundary.selectOption({value:'1'});
 await page.getByRole('button',{name:'重试停顿操作',exact:true}).waitFor();
 assert.equal(await boundary.isDisabled(),true);
 await page.waitForFunction(()=>window.fixture.audio.arrangement.pauses[0]?.afterIndex===1);
 await page.getByRole('button',{name:'重试停顿操作',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('select[id$="-boundary"]')?.value==='1');
 assert.equal(await page.evaluate(()=>window.fixture.audio.arrangement.revision),2);
 const calls=await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit').slice(-2));
 assert.equal(calls[0].args.operationId,calls[1].args.operationId);
 assert.equal(calls[0].args.expectedRevision,calls[1].args.expectedRevision);
 assert.deepEqual(await page.evaluate(()=>window.fixture.audio.arrangement.pauses),[{afterIndex:1,durationMs:500}]);
 // The host acknowledges the next move, but every follow-up status read fails.
 await page.evaluate(()=>{window.fixture.failAudioRead=true;});
 await boundary.selectOption({value:'2'});
 await page.waitForFunction(()=>document.querySelector('select[id$="-boundary"]')?.value==='2');
 assert.deepEqual(await page.evaluate(()=>window.fixture.audio.arrangement.pauses),[{afterIndex:2,durationMs:500}]);
 assert.equal(await page.getByRole('button',{name:'重试停顿操作',exact:true}).count(),0);
 await page.evaluate(()=>{window.fixture.failAudioRead=false;});
 const seconds=page.getByRole('spinbutton',{name:'额外停顿（秒）'});
 await seconds.fill('0.65');
 const beforeClose=await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit').length);
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 await seconds.waitFor({state:'hidden',timeout:5000});
 assert.equal(await page.evaluate(()=>window.fixture.audio.arrangement.pauses.find(p=>p.afterIndex===2)?.durationMs),650);
 assert.equal(await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit').length),beforeClose+1);
 await track.getByRole('button',{name:'片段 3 后的停顿',exact:true}).click();
 await seconds.waitFor();
 await seconds.fill('0.75');
 await track.getByRole('button',{name:'片段 1 后的停顿',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('select[id$="-boundary"]')?.value==='0');
 assert.equal(await page.evaluate(()=>window.fixture.audio.arrangement.pauses.find(p=>p.afterIndex===2)?.durationMs),750);
 const afterSave=await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit').length);
 await track.getByRole('button',{name:'片段 3 后的停顿',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('select[id$="-boundary"]')?.value==='2');
 assert.equal(await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit').length),afterSave, 'opening an empty boundary does not create a pause');
 await seconds.fill('11');
 assert.equal(await page.evaluate(() => { const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }),true);
 await page.evaluate(async () => await window.fixture.fireWindowClose());
 assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'confirm_window_close').length),0);
 assert.equal(await seconds.inputValue(),'11');
 const before=await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit').length);
 await track.getByRole('button',{name:'片段 1 后的停顿',exact:true}).click();
 assert.equal(await seconds.inputValue(),'11');
 assert.equal(await boundary.inputValue(),'2');
 await page.getByRole('button',{name:'下一章',exact:true}).click();
 await page.waitForTimeout(100);
 assert.equal(await seconds.inputValue(),'11');
 assert.equal(await page.getByRole('main',{name:'章节工作台'}).getAttribute('data-chapter-id'),'chapter-0');
 assert.equal(await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit').length),before);
 await page.evaluate(()=>{window.fixture.audio.run.status='succeeded'; window.fixture.audio.run.currentIndex=null; window.fixture.audio.run.revision++;});
 const generate=page.getByRole('button',{name:'重新生成本章音频',exact:true});
 await page.waitForFunction(()=>{const b=document.querySelector('button[aria-label="重新生成本章音频"]'); return b && !b.disabled;});
 const starts=await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_start').length);
 await generate.click();
 assert.equal(await seconds.inputValue(),'11');
 assert.equal(await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='chapter_audio_start').length),starts);
 await page.locator('[aria-label="工程首页"]').click();
 await page.waitForTimeout(100);
 assert.match(page.url(), /\/project\/fixture-project/);
 assert.equal(await seconds.inputValue(),'11');
 const closeTab=page.getByRole('button',{name:'关闭工程标签：山海之间'});
 await closeTab.click();
 await page.waitForTimeout(100);
 assert.equal(await closeTab.count(),1);
 assert.match(page.url(), /\/project\/fixture-project/);
 assert.equal(await seconds.inputValue(),'11');
 await page.getByRole('button',{name:'放弃修改并关闭',exact:true}).click();
 await seconds.waitFor({state:'hidden'});
 assert.equal(await page.evaluate(() => { const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }),false);
 await page.getByRole('button',{name:'下一章',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.chapterId==='chapter-1');
 await page.getByRole('button',{name:'上一章',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('main')?.dataset.chapterId==='chapter-0');
 await track.getByRole('button',{name:'片段 3 后的停顿',exact:true}).click();
 await seconds.waitFor();
 await seconds.fill('0.85');
 await page.evaluate(async () => await window.fixture.fireWindowClose());
 await page.waitForFunction(() => window.fixture.calls.some(c => c.command === 'confirm_window_close'));
 assert.equal(await page.evaluate(()=>window.fixture.audio.arrangement.pauses.find(p=>p.afterIndex===2)?.durationMs),850);
 await seconds.fill('0.9');
 await closeTab.click();
 await page.waitForURL('http://localhost:1437/');
 assert.equal(await page.evaluate(()=>window.fixture.audio.arrangement.pauses.find(p=>p.afterIndex===2)?.durationMs),900);
 console.log('PASS pause response-loss replay and acknowledged moves despite failed snapshot reads');
} catch(error) {console.error(JSON.stringify(await page.evaluate(()=>({audio:window.fixture.audio, flag:window.fixture.losePauseReply, select:document.querySelector('select[id$="-boundary"]')?.value, disabled:document.querySelector('select[id$="-boundary"]')?.disabled, calls:window.fixture.calls.filter(c=>c.command==='chapter_audio_arrangement_edit')})))); console.error((await page.locator('body').innerText()).slice(-1800)); throw error;} finally {await browser.close();}
});
