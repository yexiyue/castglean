import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("reading-toolbar", async ({ flowBrowser: browser }) => {
const errors = [];
try {
  for (const locale of ["zh", "en"]) for (const theme of ["light", "dark"]) for (const width of [1440, 1024]) {
    const page = await browser.newPage({ viewport: { width, height: 780 } });
    page.setDefaultTimeout(15000);
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(`http://localhost:1437/project/fixture-project?fixture=desktop&largeDirectory=1&grouped=1&locale=${locale}&theme=${theme}`);
    const zh = locale === "zh";
    const main = page.getByRole("main", { name: zh ? "章节工作台" : "Chapter workspace" });
    await main.waitFor();
    const tree = page.getByRole("tree");
    if (!await tree.isVisible()) await page.getByRole("button", { name: zh ? "目录" : "Directory", exact: true }).click();
    const search = page.getByRole("searchbox", { name: zh ? "搜索章节或目录序号" : "Search chapters or directory position" });
    const reads = () => page.evaluate(() => window.fixture.calls.filter(call => call.command === "local_project_text").length);
    await page.locator('[data-slot="source-scroll"][aria-busy="false"]').waitFor();
    const before = await reads();
    await search.fill("2200");
    await tree.getByRole("treeitem").last().waitFor();
    assert.equal(await reads(), before, "filtering does not read source");
    await search.press("Enter");
    await page.waitForFunction(() => window.fixture.calls.some(call => call.command === "local_project_text" && call.args.line >= 21988));
    await search.fill("not-a-chapter");
    await page.getByText(zh ? "没有匹配的章节" : "No matching chapters", { exact: true }).waitFor();
    await search.press("Escape");
    assert.equal(await search.inputValue(), "");
    const info = page.getByRole("button", { name: zh ? "原文信息" : "Source information", exact: true });
    await info.focus(); await info.press("Enter");
    const panel = page.locator('[data-slot="popover-content"]');
    await panel.waitFor();
    assert.match(await panel.innerText(), /\.txt/);
    await page.keyboard.press("Escape");
    await panel.waitFor({ state: "hidden" });
    assert.equal(await info.evaluate(el => el === document.activeElement), true);
    const compact = page.getByRole("button", { name: zh ? "切换为原样显示" : "Show original spacing", exact: true });
    assert.equal(await compact.getAttribute("aria-pressed"), "true");
    const compactBox = await compact.boundingBox();
    await compact.focus(); await compact.press("Space");
    const original = page.getByRole("button", { name: zh ? "切换为紧凑显示" : "Show compact spacing", exact: true });
    assert.equal(await original.getAttribute("aria-pressed"), "false");
    assert.deepEqual(await original.boundingBox(), compactBox);
    const go = page.getByRole("button", { name: zh ? "转到行" : "Go to line", exact: true });
    await go.click();
    const dialog = page.getByRole("dialog", { name: zh ? "转到行" : "Go to line" });
    const line = dialog.getByRole("spinbutton", { name: zh ? "原文行号" : "Source line number" });
    await line.fill("0"); await line.press("Enter");
    await dialog.getByText(zh ? "请输入有效行号。" : "Enter a valid line number.").waitFor();
    await line.fill("12"); await line.press("Enter");
    await dialog.waitFor({ state: "hidden" });
    await page.waitForFunction(() => window.fixture.calls.some(call => call.command === "local_project_text" && call.args.line === 11));
    await page.keyboard.press(process.platform === "darwin" ? "Meta+g" : "Control+g");
    await dialog.waitFor();
    assert.equal(await line.inputValue(), "12");
    assert.equal(await line.evaluate(el => el === document.activeElement), true);
    await page.keyboard.press("Escape");
    await dialog.waitFor({ state: "hidden" });
    await page.getByRole("button", { name: zh ? "分卷设置" : "Volume settings", exact: true }).click();
    const volume = page.getByRole("dialog", { name: zh ? "分卷设置" : "Volume settings" });
    await volume.waitFor(); await page.keyboard.press("Escape"); await volume.waitFor({ state: "hidden" });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(await page.evaluate(() => window.fixture.unexpected), []);
    await page.close();
  }
  assert.deepEqual(errors, []);
  console.log("PASS actual reading toolbar, directory search, focus and explicit navigation across 8 locale/theme/width combinations");
} finally { await browser.close(); }
});
