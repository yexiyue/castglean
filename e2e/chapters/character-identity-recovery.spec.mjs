import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("character-identity-recovery", async ({ flowBrowser: browser }) => {
const page = await browser.newPage();
page.setDefaultTimeout(15000);
try {
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&windowFixture=1");
  await page.getByRole("button", { name: "工程角色", exact: true }).click();
  await page.getByRole("button", { name: /阿岚/ }).first().click();
  await page.getByRole("tab", { name: "身份" }).click();
  await page.getByRole("button", { name: "重命名" }).click();
  await page.getByLabel("共享显示名称").fill("新角色名");
  await page.evaluate(() => { window.fixture.loseCharacterReply = true; });
  await page.getByRole("button", { name: "确认更名" }).click();
  await page.getByRole("button", { name: "重试原身份操作" }).waitFor();
  assert.equal(await page.evaluate(() => window.fixture.characterWrites), 1);
  await page.waitForFunction(() => typeof window.fixture.fireWindowClose === "function");
  await page.evaluate(() => window.fixture.fireWindowClose());
  await page.getByText("角色资料有未保存草稿或待核对操作；关闭后草稿及原操作身份可能丢失。").waitFor();
  await page.getByRole("button", { name: "继续使用" }).click();
  await page.getByRole("link", { name: "工程首页" }).click();
  await page.goBack();
  await page.getByRole("button", { name: "重试原身份操作" }).click();
  await page.getByRole("button", { name: "重试原身份操作" }).waitFor({ state: "hidden" });
  const calls = await page.evaluate(() => window.fixture.calls.filter(call => call.command === "chapter_analysis_character_edit"));
  assert.equal(calls.length, 2);
  assert.deepEqual(calls[0].args, calls[1].args);
  assert.equal(await page.evaluate(() => window.fixture.characterWrites), 1);
  await page.getByRole("button", { name: "工程角色", exact: true }).click();
  await page.getByRole("button", { name: /新角色名/ }).first().click();
  await page.getByRole("tab", { name: "身份" }).click();
  await page.getByRole("button", { name: "重命名" }).click();
  await page.getByLabel("共享显示名称").fill("再更名");
  await page.evaluate(() => { window.fixture.failCharacterReadAfterWrite = true; });
  await page.getByRole("button", { name: "确认更名" }).click();
  await page.getByText("身份修改已保存，重新读取状态失败。").waitFor();
  await page.evaluate(() => { window.fixture.failCharacterReadAfterWrite = false; window.fixture.failCharacterUsage = false; });
  await page.getByRole("button", { name: "重试读取身份" }).click();
  await page.getByText("身份修改已保存，重新读取状态失败。").waitFor({ state: "hidden" });
  assert.equal(await page.evaluate(() => window.fixture.characterWrites), 2);
  await page.getByLabel("共享显示名称").fill("晚到的名称");
  await page.evaluate(() => { window.fixture.delayCharacterEdit = true; });
  await page.getByRole("button", { name: "确认更名" }).click();
  await page.waitForFunction(() => typeof window.fixture.releaseCharacterEdit === "function");
  await page.getByLabel("共享显示名称").fill("继续输入的草稿");
  await page.evaluate(() => window.fixture.releaseCharacterEdit());
  await page.getByText("角色名称已变化，草稿仍保留；请先核对当前名称。").waitFor();
  assert.equal(await page.getByLabel("共享显示名称").inputValue(), "继续输入的草稿");
  console.log("PASS character identity receipt recovery across routes");
} finally { await browser.close(); }
});
