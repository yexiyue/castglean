import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("character-design", async ({ flowBrowser: browser }) => {
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(15000);
try {
  const chooseCharacter = async (card) => {
    const input = card.getByLabel("改选绑定目标");
    await input.fill("阿岚");
    await page.getByRole("option", { name: "阿岚", exact: true }).waitFor();
    assert.equal(await input.getAttribute("aria-activedescendant"), null);
    await input.press("Enter");
    assert.equal(await input.inputValue(), "阿岚");
    assert.equal(await input.getAttribute("aria-expanded"), "true");
    assert.equal(await card.locator("button").filter({ hasText: /^绑定到此目标$/ }).isDisabled(), true);
    await input.press("ArrowDown");
    await page.waitForFunction(input => document.getElementById(input.getAttribute("aria-activedescendant"))?.textContent === "阿岚", await input.elementHandle());
    await input.press("Enter");
    await page.waitForFunction(article => {
      const input = article.querySelector('input[aria-label="改选绑定目标"]');
      const button = [...article.querySelectorAll("button")].find(el => el.textContent.trim() === "绑定到此目标");
      return input?.value === "阿岚" && button && !button.disabled;
    }, await card.elementHandle());
  };
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&voiceAudition=1&designCandidate=1&designAvailability=1");
  await page.getByRole("button", { name: "工程角色", exact: true }).click();
  const selectedRow = page.locator('button[aria-current="true"]');
  await selectedRow.waitFor();
  assert.deepEqual(await selectedRow.evaluate(el => { const s = getComputedStyle(el); return [s.paddingLeft, s.paddingTop, s.borderRadius]; }), ["12px", "8px", "0px"]);
  await page.getByRole("button", { name: "设计音色", exact: true }).click();
  let dialog = page.getByRole("dialog", { name: "为「旁白」设计音色" });
  assert.equal(await dialog.evaluate(el => getComputedStyle(el).maxHeight), "720px");
  assert.equal(await dialog.evaluate(el => getComputedStyle(el).display), "flex");
  await dialog.getByLabel("声音描述").fill("旁白设计草稿");
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), true);
  await dialog.getByLabel("设计引擎").selectOption("other-design");
  await dialog.getByLabel("计算设备").selectOption("Metal");
  await dialog.getByRole("button", { name: "暂时关闭", exact: true }).click();
  await page.getByRole("button", { name: "设计音色", exact: true }).click();
  dialog = page.getByRole("dialog", { name: "为「旁白」设计音色" });
  assert.equal(await dialog.getByLabel("声音描述").inputValue(), "旁白设计草稿");
  assert.equal(await dialog.getByLabel("计算设备").inputValue(), "Metal");
  assert.equal(await page.evaluate(() => window.fixture.calls.some(call => call.command === "start_voice_job")), false);
  await dialog.getByRole("button", { name: "暂时关闭" }).click();
  await page.evaluate(() => window.fixture.setDesignDeviceAvailable(false));
  await page.getByRole("link", { name: "工程首页" }).click();
  await page.goBack();
  await page.getByRole("button", { name: "工程角色", exact: true }).click();
  await page.getByRole("button", { name: "设计音色", exact: true }).click();
  dialog = page.getByRole("dialog", { name: "为「旁白」设计音色" });
  await dialog.getByText("已选设备不可用，请重新选择或等待其恢复。").waitFor();
  assert.equal(await dialog.getByRole("button", { name: "生成音色候选" }).isDisabled(), true);
  await dialog.getByRole("button", { name: "暂时关闭" }).click();
  await page.evaluate(() => window.fixture.setDesignDeviceAvailable(true));
  await page.getByRole("link", { name: "工程首页" }).click();
  await page.goBack();
  await page.getByRole("button", { name: "工程角色", exact: true }).click();
  await page.getByRole("button", { name: "设计音色", exact: true }).click();
  dialog = page.getByRole("dialog", { name: "为「旁白」设计音色" });
  assert.equal(await dialog.getByLabel("计算设备").inputValue(), "Metal");
  await page.evaluate(() => { window.fixture.loseAuditionReply = true; });
  await dialog.getByRole("button", { name: "生成音色候选" }).click();
  await page.getByRole("button", { name: "重试「旁白」的原请求" }).click();
  await page.getByRole("button", { name: "重试「旁白」的原请求" }).waitFor({ state: "hidden" });
  let card = page.getByRole("article", { name: "旁白" });
  await page.evaluate(() => { window.fixture.loseCandidateSave = true; });
  await card.getByRole("button", { name: "保存到音色库" }).click();
  await page.getByRole("button", { name: "读取候选「旁白 · design-1」状态" }).click();
  await page.getByText("当前候选已在音色库中，请核对后继续。").waitFor();
  await page.getByRole("button", { name: "重试候选「旁白 · design-1」的原操作" }).click();
  await card.getByLabel("改选绑定目标").waitFor();
  assert.equal(await card.getByLabel("改选绑定目标").inputValue(), "旁白");
  await card.getByLabel("改选绑定目标").fill("不存在的角色");
  await page.getByText("没有匹配的角色").waitFor();
  assert.equal(await card.locator("button").filter({ hasText: /^绑定到此目标$/ }).isDisabled(), true);
  await card.getByLabel("改选绑定目标").press("Escape");
  assert.equal(await card.getByLabel("改选绑定目标").inputValue(), "旁白");
  assert.equal(await card.getByRole("button", { name: "绑定到此目标" }).isEnabled(), true);
  await chooseCharacter(card);
  await page.getByRole("button", { name: /阿岚/ }).first().click();
  assert.equal(await page.getByRole("article", { name: "旁白" }).count(), 0);
  await page.getByRole("button", { name: "设计音色", exact: true }).click();
  dialog = page.getByRole("dialog", { name: "为「阿岚」设计音色" });
  assert.equal(await dialog.getByLabel("声音描述").inputValue(), "");
  await dialog.getByLabel("声音描述").fill("角色设计草稿");
  await dialog.getByRole("button", { name: "生成音色候选" }).click();
  await page.getByRole("article", { name: "阿岚" }).waitFor();
  await page.getByRole("button", { name: /旁白/ }).first().click();
  card = page.getByRole("article", { name: "旁白" });
  assert.equal(await card.getByLabel("改选绑定目标").inputValue(), "阿岚");
  assert.equal(await page.getByRole("article", { name: "阿岚" }).count(), 0);
  await page.getByRole("link", { name: "工程首页" }).click();
  await page.goBack();
  await page.getByRole("button", { name: "工程角色", exact: true }).click();
  card = page.getByRole("article", { name: "旁白" });
  await card.waitFor();
  assert.equal(await card.getByLabel("改选绑定目标").inputValue(), "阿岚");
  const calls = await page.evaluate(() => window.fixture.calls.filter(call => call.command === "start_voice_job"));
  assert.equal(calls.length, 3);
  assert.deepEqual(calls[0].args, calls[1].args);
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&unattributedCandidate=1");
  await page.getByRole("button", { name: "工程角色", exact: true }).click();
  const unknown = page.getByRole("article", { name: "独立候选" });
  await unknown.waitFor();
  assert.equal(await unknown.getByLabel("改选绑定目标").inputValue(), "");
  assert.equal(await unknown.getByRole("button", { name: "绑定到此目标" }).isDisabled(), true);
  await chooseCharacter(unknown);
  assert.equal(await unknown.getByRole("button", { name: "绑定到此目标" }).isEnabled(), true);
  await unknown.getByRole("button", { name: "绑定到此目标" }).click();
  await page.waitForFunction(() => window.fixture.calls.some(call => call.command === "voice_binding_edit"));
  const binding = await page.evaluate(() => window.fixture.calls.find(call => call.command === "voice_binding_edit").args);
  assert.equal(binding.target.character_id, "character-a");
  assert.equal(binding.edit.voice.id, "saved-external");
  console.log("PASS character design drafts, receipt recovery and candidate target isolation");
} finally { await browser.close(); }
});
