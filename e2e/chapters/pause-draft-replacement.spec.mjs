import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("pause-draft-replacement", async ({ flowBrowser: browser }) => {
const page = await browser.newPage();
page.setDefaultTimeout(30000);
try {
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&audio=1&windowFixture=1");
  await page.getByRole("button", { name: "分析本章", exact: true }).click();
  await page.locator("[data-segment-id]").first().waitFor();
  await page.getByRole("button", { name: "生成本章音频", exact: true }).click();
  const track = page.getByRole("region", { name: "章节音频轨道" });
  await track.locator('[data-unit-index="0"]').click();
  await track.getByRole("button", { name: "添加停顿", exact: true }).click();
  await page.waitForFunction(() => window.fixture.audio.arrangement.revision === 1);
  const input = page.getByRole("spinbutton", { name: "额外停顿（秒）" });
  await input.fill("11");
  const writes = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_arrangement_edit").length);
  await track.getByRole("button", { name: "撤销停顿修改", exact: true }).click();
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_arrangement_edit").length), writes);
  assert.equal(await input.inputValue(), "11");
  await page.evaluate(() => { window.fixture.emptyAudioStatus = true; window.fixture.audio.run.status = "succeeded"; });
  await page.locator('[data-slot="chapter-audio-track"]').waitFor({ state: "hidden" });
  assert.equal(await input.inputValue(), "11");
  assert.equal(await page.evaluate(() => { const e = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(e); return e.defaultPrevented; }), true);
  await page.evaluate(() => {
    const state = window.fixture.audio;
    window.fixture.emptyAudioStatus = false;
    state.run.id = "replacement-run";
    state.run.revision++;
    state.arrangement = { runId: "replacement-run", revision: 0, pauses: [], canUndo: false, stale: false };
  });
  await page.locator('[data-slot="chapter-audio-track"][data-run-id="replacement-run"]').waitFor();
  assert.equal(await input.inputValue(), "11");
  await page.getByText("音频版本已变化；此输入仍属于原音频版本。").waitFor();
  await page.getByRole("button", { name: "放弃修改并关闭" }).click();
  await input.waitFor({ state: "hidden" });
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_arrangement_edit").length), writes);
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&audio=1&windowFixture=1");
  await page.getByRole("button", { name: "分析本章", exact: true }).click();
  await page.locator("[data-segment-id]").first().waitFor();
  await page.getByRole("button", { name: "生成本章音频", exact: true }).click();
  await track.locator('[data-unit-index="0"]').click();
  await track.getByRole("button", { name: "添加停顿", exact: true }).click();
  await page.waitForFunction(() => window.fixture.audio.arrangement.revision === 1);
  const oldRun = await page.evaluate(() => window.fixture.audio.run.id);
  await input.fill("0.75");
  await page.evaluate(() => {
    const state = window.fixture.audio;
    state.run.id = "replacement-run";
    state.run.revision++;
    state.arrangement = { runId: "replacement-run", revision: 0, pauses: [], canUndo: false, stale: false };
  });
  await page.locator('[data-slot="chapter-audio-track"][data-run-id="replacement-run"]').waitFor();
  assert.equal(await input.inputValue(), "0.75");
  await input.press("Enter");
  await page.getByRole("button", { name: "重试保存停顿" }).waitFor();
  const attempted = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_arrangement_edit").at(-1).args);
  assert.equal(attempted.runId, oldRun);
  assert.equal(attempted.edit.duration_ms, 750);
  assert.deepEqual(await page.evaluate(() => window.fixture.audio.arrangement.pauses), []);
  await page.getByRole("button", { name: "放弃修改并关闭" }).click();
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&audio=1&windowFixture=1");
  await page.getByRole("button", { name: "分析本章", exact: true }).click();
  await page.locator("[data-segment-id]").first().waitFor();
  await page.getByRole("button", { name: "生成本章音频", exact: true }).click();
  await track.locator('[data-unit-index="0"]').click();
  await track.getByRole("button", { name: "添加停顿", exact: true }).click();
  await page.waitForFunction(() => window.fixture.audio.arrangement.revision === 1);
  await input.fill("0.75");
  const reads = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_status").length);
  await page.evaluate(() => {
    window.fixture.audio.arrangement.revision++;
    window.fixture.audio.arrangement.pauses[0].durationMs = 900;
  });
  await page.waitForFunction(n => window.fixture.calls.filter(c => c.command === "chapter_audio_status").length > n, reads);
  await input.press("Enter");
  await page.getByRole("button", { name: "重试保存停顿" }).waitFor();
  const concurrent = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "chapter_audio_arrangement_edit").at(-1).args);
  assert.equal(concurrent.expectedRevision, 1);
  assert.equal(await input.inputValue(), "0.75");
  assert.equal(await page.evaluate(() => window.fixture.audio.arrangement.pauses[0].durationMs), 900);
  await page.getByRole("button", { name: "放弃修改并关闭" }).click();
  console.log("PASS pause drafts retain original run and revision through replacement and concurrent edits");
} finally { await browser.close(); }
});
