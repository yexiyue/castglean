import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("pause-form", async ({ flowBrowser: browser }) => {
try {
  const page = await browser.newPage();
  await page.goto("http://localhost:1437/__pause-form");
  const input = page.getByLabel("额外停顿（秒）", { exact: true });
  const outside = page.getByRole("button", { name: "外部焦点" });
  const calls = page.getByLabel("calls");
  assert.equal(await input.getAttribute("role"), "spinbutton");
  assert.equal(await input.getAttribute("aria-valuemin"), "0");
  assert.equal(await input.getAttribute("aria-valuemax"), "10");
  assert.equal(await input.getAttribute("aria-valuenow"), "0.5");
  const hintId = await input.getAttribute("aria-describedby");
  assert.match(await page.locator(`[id="${hintId}"]`).textContent(), /范围 0–10 秒/);
  await page.getByRole("button", { name: "切换忙碌状态" }).click();
  assert.equal(await input.isDisabled(), true);
  await page.getByRole("button", { name: "切换忙碌状态" }).click();
  await page.getByRole("button", { name: "设置外部数值" }).click();
  assert.equal(await input.inputValue(), "0.25");
  assert.equal(await input.getAttribute("aria-valuenow"), "0.25");
  assert.equal(JSON.parse(await calls.textContent()).length, 0);
  await input.fill("0.75");
  await outside.click();
  await page.waitForFunction(() => document.querySelector("output")?.textContent?.includes('"duration_ms":750'));
  await page.waitForTimeout(250);
  assert.equal(JSON.parse(await calls.textContent()).length, 1);
  for (const value of ["11", "", "-1", "0.755"]) {
    await input.fill(value);
    await outside.click();
    assert.equal(await input.getAttribute("aria-invalid"), "true", value);
    assert.equal(await page.getByRole("alert").count(), 1, value);
    assert.equal(await input.inputValue(), value, value);
    assert.equal(JSON.parse(await calls.textContent()).length, 1, value);
  }
  await input.fill("0.75");
  await input.press("ArrowUp");
  await outside.click();
  await page.waitForFunction(() => document.querySelector("output")?.textContent?.includes('"duration_ms":760'));
  await page.waitForTimeout(250);
  await input.fill("0.8");
  await input.dispatchEvent("compositionstart", { data: "" });
  await input.press("Enter");
  assert.equal(JSON.parse(await calls.textContent()).length, 2);
  await outside.click();
  assert.equal(JSON.parse(await calls.textContent()).length, 2);
  await input.dispatchEvent("compositionend", { data: "" });
  await input.focus();
  await outside.click();
  await page.waitForFunction(() => document.querySelector("output")?.textContent?.includes('"duration_ms":800'));
  await page.waitForTimeout(250);
  await input.fill("0.9");
  await page.getByRole("button", { name: "关闭", exact: true }).click();
  assert.equal(await page.getByLabel("closed").textContent(), "0");
  await page.waitForFunction(() => document.querySelector('[aria-label="closed"]')?.textContent === "1");
  assert.equal(JSON.parse(await calls.textContent()).filter((call) => call.duration_ms === 900).length, 1);
  await input.fill("11");
  await page.getByRole("button", { name: "关闭", exact: true }).click();
  assert.equal(await page.getByLabel("closed").textContent(), "1");
  assert.equal(await input.inputValue(), "11");
  await page.getByRole("button", { name: "放弃修改并关闭" }).click();
  assert.equal(await page.getByLabel("closed").textContent(), "2");
  await page.getByRole("button", { name: "切换保存失败" }).click();
  await input.fill("1.2");
  await outside.click();
  await page.getByRole("button", { name: "重试保存停顿" }).waitFor();
  await page.getByRole("button", { name: "关闭", exact: true }).click();
  assert.equal(await page.getByLabel("closed").textContent(), "2");
  assert.equal(await input.inputValue(), "1.2");
  assert.equal(JSON.parse(await calls.textContent()).filter((call) => call.duration_ms === 1200).length, 1);
  await page.getByRole("button", { name: "切换保存失败" }).click();
  await input.fill("1.3");
  await input.press("Enter");
  await page.waitForFunction(() => document.querySelector('output[aria-label="calls"]')?.textContent?.includes('"duration_ms":1300'));
  await page.waitForTimeout(250);
  assert.equal(JSON.parse(await calls.textContent()).filter((call) => call.duration_ms === 1300).length, 1);
  console.log("PASS pause validation, direct out-of-range input and stepping");
} finally { await browser.close(); }
});
