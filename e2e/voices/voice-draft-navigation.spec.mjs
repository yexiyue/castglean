import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("voice-draft-navigation", async ({ flowBrowser: browser }) => {
const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
page.setDefaultTimeout(20000);
try {
  await page.goto("http://localhost:1437/voices?fixture=desktop&manyVoices=1&library=mine&windowFixture=1");
  const open = async (name) => {
    await page.getByRole("button", { name: `查看音色「${name}」` }).click();
    await page.getByRole("button", { name: "管理音色", exact: true }).click();
    await page.getByRole("textbox", { name: "音色名称" }).waitFor();
  };
  await open("山风");
  await page.getByRole("textbox", { name: "音色名称" }).fill("山风草稿");
  await page.getByRole("textbox", { name: "声音描述" }).fill("山风描述草稿");
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), true);
  await page.waitForFunction(() => typeof window.fixture.fireWindowClose === "function");
  await page.evaluate(() => window.fixture.fireWindowClose());
  await page.getByText("音色修改尚未保存或确认。关闭后草稿和本次会话的恢复凭据会丢失，无法安全重试原操作。").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(call => call.command === "confirm_window_close").length), 0);
  await page.getByRole("button", { name: "继续使用" }).click();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "管理音色", exact: true }).click();
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "山风描述草稿");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await open("海潮");
  assert.equal(await page.getByRole("textbox", { name: "音色名称" }).inputValue(), "海潮");
  await page.getByRole("textbox", { name: "音色名称" }).fill("海潮草稿");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await open("山风");
  assert.equal(await page.getByRole("textbox", { name: "音色名称" }).inputValue(), "山风草稿");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "山风描述草稿");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "模型中心", exact: true }).click();
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "音色中心", exact: true }).click();
  await page.getByRole("tab", { name: "我的音色" }).click();
  await open("山风");
  assert.equal(await page.getByRole("textbox", { name: "音色名称" }).inputValue(), "山风草稿");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "山风描述草稿");
  await page.getByRole("button", { name: "撤销修改" }).first().click();
  await page.getByRole("button", { name: "撤销修改" }).last().click();
  assert.equal(await page.getByRole("textbox", { name: "音色名称" }).inputValue(), "山风");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "柔和的讲述声");
  await page.evaluate(() => { window.fixture.delayVoiceEdit = true; });
  await page.getByRole("textbox", { name: "音色名称" }).fill("新山风");
  await page.getByRole("button", { name: "保存名称" }).click();
  await page.waitForFunction(() => typeof window.fixture.releaseVoiceEdit === "function");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "模型中心", exact: true }).click();
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "音色中心", exact: true }).click();
  await page.getByRole("tab", { name: "我的音色" }).click();
  await open("山风");
  assert.equal(await page.getByRole("textbox", { name: "音色名称" }).isDisabled(), true);
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).isDisabled(), true);
  await page.evaluate(() => window.fixture.releaseVoiceEdit());
  await page.getByRole("textbox", { name: "音色名称" }).waitFor({ state: "visible" });
  await page.waitForFunction(() => [...document.querySelectorAll('input[aria-invalid]')].some(input => input.value === "新山风" && !input.disabled));
  assert.equal(await page.getByRole("button", { name: "保存名称" }).isDisabled(), true);
  const writes = await page.evaluate(() => window.fixture.calls.filter(call => call.command === "rename_library_voice"));
  assert.equal(writes.length, 1);
  assert.equal(writes[0].args.id, "fixture-voice");
  assert.equal(writes[0].args.name, "新山风");
  assert.match(writes[0].args.operationId, /^[0-9a-f-]{36}$/);
  await page.getByRole("textbox", { name: "声音描述" }).fill("新描述");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.getByText("描述已保存。", { exact: true }).waitFor();
  await page.waitForFunction(() => window.fixture.calls.some(call => call.command === "describe_library_voice"));
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await open("新山风");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "新描述");
  await page.evaluate(() => { window.fixture.failVoiceEdit = true; });
  await page.getByRole("textbox", { name: "声音描述" }).fill("失败草稿");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.getByText("上次音色修改的结果尚未确认。重试会使用原操作身份。").waitFor();
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await page.getByText("音色「新山风」的修改尚未确认。").waitFor();
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "模型中心", exact: true }).click();
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "音色中心", exact: true }).click();
  await page.getByRole("tab", { name: "我的音色" }).click();
  await page.getByRole("button", { name: "查看音色，在管理音色中核对" }).click();
  await page.getByRole("button", { name: "管理音色", exact: true }).click();
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "失败草稿");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).isDisabled(), true);
  await page.getByRole("button", { name: "读取当前音色" }).click();
  await page.getByText("当前值与提交内容不同，原操作仍未确认。").waitFor();
  await page.evaluate(() => window.fixture.changeVoiceDescription("fixture-voice", "后台新描述"));
  await page.getByRole("button", { name: "采用当前值并放弃本次修改" }).click();
  await page.getByText("音色内容已变化，请再次确认当前值。").waitFor();
  await page.locator("p").filter({ hasText: "后台新描述" }).waitFor();
  await page.getByRole("button", { name: "采用当前值并放弃本次修改" }).click();
  await open("新山风");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "后台新描述");
  await page.evaluate(() => { window.fixture.failVoiceEdit = false; window.fixture.delayVoiceEdit = true; delete window.fixture.releaseVoiceEdit; });
  await page.getByRole("textbox", { name: "声音描述" }).fill("失败草稿");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.waitForFunction(() => typeof window.fixture.releaseVoiceEdit === "function");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await open("新山风");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).isDisabled(), true);
  await page.evaluate(() => window.fixture.releaseVoiceEdit());
  await page.waitForFunction(() => [...document.querySelectorAll("textarea")].some(input => input.value === "失败草稿" && !input.disabled));
  await page.waitForFunction(() => [...document.querySelectorAll("button")].some(button => button.textContent.trim() === "保存描述" && button.disabled));
  await page.evaluate(() => { window.fixture.loseVoiceReply = true; });
  await page.getByRole("textbox", { name: "声音描述" }).fill("已写入但丢失回执");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.getByText("上次音色修改的结果尚未确认。重试会使用原操作身份。").waitFor();
  const count = await page.evaluate(() => window.fixture.calls.filter(call => call.command === "describe_library_voice").length);
  await page.evaluate(() => { window.fixture.failVoiceRead = true; });
  await page.getByRole("button", { name: "读取当前音色" }).click();
  await page.getByText("无法读取当前音色，请重试。").waitFor();
  assert.equal(await page.getByRole("button", { name: "采用当前值并放弃本次修改" }).count(), 0);
  await page.evaluate(() => { window.fixture.failVoiceRead = false; });
  await page.getByRole("button", { name: "读取当前音色" }).click();
  await page.getByText("当前值与提交内容一致，但没有收到原操作的确认。").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(call => call.command === "describe_library_voice").length), count);
  await page.getByRole("button", { name: "采用当前值并放弃本次修改" }).click();
  await open("新山风");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "已写入但丢失回执");
  await page.evaluate(() => { window.fixture.loseVoiceReply = true; });
  await page.getByRole("textbox", { name: "音色名称" }).fill("回执丢失后的名称");
  await page.getByRole("button", { name: "保存名称" }).click();
  await page.getByText("上次音色修改的结果尚未确认。重试会使用原操作身份。").waitFor();
  const renameCount = await page.evaluate(() => window.fixture.calls.filter(call => call.command === "rename_library_voice").length);
  await page.getByRole("button", { name: "读取当前音色" }).click();
  await page.getByText("当前值与提交内容一致，但没有收到原操作的确认。").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(call => call.command === "rename_library_voice").length), renameCount);
  await page.getByRole("button", { name: "采用当前值并放弃本次修改" }).click();
  await open("回执丢失后的名称");
  assert.equal(await page.getByRole("textbox", { name: "音色名称" }).inputValue(), "回执丢失后的名称");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await open("海潮");
  await page.evaluate(() => { window.fixture.failVoiceEdit = true; });
  await page.getByRole("textbox", { name: "声音描述" }).fill("将要删除的音色草稿");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.getByText("上次音色修改的结果尚未确认。重试会使用原操作身份。").waitFor();
  await page.keyboard.press("Escape");
  await page.keyboard.press("Escape");
  await page.evaluate(() => window.fixture.removeVoice("fixture-voice-2"));
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "模型中心", exact: true }).click();
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "音色中心", exact: true }).click();
  await page.getByRole("tab", { name: "我的音色" }).click();
  await page.getByRole("button", { name: "重新读取并放弃此音色草稿" }).click();
  await page.getByText("音色「fixture-voice-2」的修改尚未确认。").waitFor({ state: "hidden" });
  console.log("PASS library voice drafts survive nested dialog and target changes; explicit reset is scoped");
} finally { await browser.close(); }
});
