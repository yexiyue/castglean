import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("audition-form", async ({ flowBrowser: browser }) => {
const page = await browser.newPage({ viewport: { width: 1024, height: 680 } });
page.setDefaultTimeout(12000);
try {
  await page.goto("http://localhost:1437/voices/new?fixture=desktop&inspectors=1&auditionForm=1&voiceAudition=1&voiceCandidateDeletion=1&voiceLibraryDeletion=1");
  const candidate = page.getByRole("article").filter({ hasText: "山风候选" });
  const open = candidate.getByRole("button", { name: "打开试听配置" });
  await open.click();
  const dialog = page.getByRole("dialog", { name: "打开试听配置" });
  const fields = dialog.locator('[data-slot="field-group"]').first();
  const layout = await fields.evaluate(element => ({ display: getComputedStyle(element).display, columns: getComputedStyle(element).gridTemplateColumns.split(" ").length, gap: getComputedStyle(element).gap }));
  assert.deepEqual(layout, { display: "grid", columns: 2, gap: "12px" });
  const text = dialog.getByRole("textbox", { name: "试听文本" });
  const submit = dialog.getByRole("button", { name: "生成试听" });
  await text.fill("");
  await submit.click();
  await dialog.getByText("请填写试听文本。").waitFor();
  assert.equal(await text.evaluate((element) => element === document.activeElement), true);
  await text.fill("山".repeat(501));
  await submit.click();
  await dialog.getByText("试听文本不能超过 500 字符。").waitFor();
  await text.fill("  公开试听文本\n第二行  ");
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), true);
  const style = dialog.getByRole("textbox", { name: "风格指令" });
  await style.fill("青".repeat(1366));
  await submit.click();
  await dialog.getByText("风格指令不能超过 4096 字节。").waitFor();
  assert.equal(await style.evaluate((element) => element === document.activeElement), true);
  await style.fill("平静叙述");
  const model = dialog.getByRole("combobox", { name: "模型", exact: true });
  await model.selectOption("kokoro/other");
  await page.evaluate(() => window.fixture.setAuditionModelAvailable(false));
  await model.getByRole("option", { name: "已选模型不可用" }).waitFor({ state: "attached" });
  assert.equal(await submit.isDisabled(), true);
  assert.equal(await text.inputValue(), "  公开试听文本\n第二行  ");
  await page.evaluate(() => window.fixture.setAuditionModelAvailable(true));
  await page.waitForFunction((element) => element.value === "kokoro/other", await model.elementHandle());
  await model.selectOption("kokoro/kokoro");
  const device = dialog.getByRole("combobox", { name: "计算设备" });
  await device.selectOption("Metal");
  await page.evaluate(() => window.fixture.setAuditionDeviceAvailable(false));
  await dialog.getByText("已选设备不可用，请重新选择。").waitFor();
  assert.equal(await submit.isDisabled(), true);
  await page.evaluate(() => window.fixture.setAuditionDeviceAvailable(true));
  await page.waitForFunction((element) => element.value === "Metal", await device.elementHandle());
  assert.equal(await text.inputValue(), "  公开试听文本\n第二行  ");
  assert.equal(await style.inputValue(), "平静叙述");
  assert.equal(await page.evaluate(() => window.fixture.calls.some((call) => call.command === "start_voice_job")), false);
  await page.keyboard.press("Escape");
  await dialog.waitFor({ state: "hidden" });
  await open.click();
  assert.equal(await text.inputValue(), "  公开试听文本\n第二行  ");
  await page.keyboard.press("Escape");
  await page.locator('a[href="/models"]').first().click();
  await page.locator('a[href="/voices"]').first().click();
  await page.getByRole("link", { name: "创建音色", exact: true }).click();
  await page.getByRole("article").filter({ hasText: "山风候选" }).getByRole("button", { name: "打开试听配置" }).click();
  assert.equal(await text.inputValue(), "  公开试听文本\n第二行  ");
  assert.equal(await style.inputValue(), "平静叙述");
  await submit.click();
  await page.waitForFunction(() => window.fixture.calls.some((call) => call.command === "start_voice_job"));
  const request = await page.evaluate(() => window.fixture.calls.find((call) => call.command === "start_voice_job").args.request);
  assert.equal(request.kind, "audition");
  assert.equal(request.device, "Metal");
  assert.deepEqual(request.voice, { kind: "candidate", id: "fixture-candidate" });
  assert.equal(request.text, "  公开试听文本\n第二行  ");
  assert.equal(request.style, "平静叙述");
  const reset = dialog.getByRole("button", { name: "重置试听配置" });
  await page.waitForFunction((element) => !element.disabled, await reset.elementHandle());
  await reset.click();
  assert.notEqual(await text.inputValue(), "  公开试听文本\n第二行  ");
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), false);
  await text.fill("候选删除后不再保留的草稿");
  await page.keyboard.press("Escape");
  await dialog.waitFor({ state: "hidden" });
  const currentCandidate = page.getByRole("article").filter({ hasText: "山风候选" });
  await currentCandidate.getByRole("button", { name: "移除候选" }).click();
  await page.getByRole("alertdialog", { name: "移除这个候选？" }).getByRole("button", { name: "确认移除" }).click();
  await currentCandidate.waitFor({ state: "hidden" });
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), false);
  await page.locator('a[href="/voices"]').first().click();
  await page.getByRole("tab", { name: "我的音色" }).click();
  await page.getByRole("button", { name: "查看音色「山风」" }).click();
  const voiceDialog = page.getByRole("dialog", { name: "山风" });
  await voiceDialog.getByRole("textbox", { name: "试听文本" }).fill("库音色删除后的草稿");
  await voiceDialog.getByRole("button", { name: "管理音色" }).click();
  await page.getByRole("dialog", { name: "管理音色" }).getByRole("button", { name: "删除音色…" }).click();
  await voiceDialog.waitFor({ state: "hidden" });
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), false);
  await page.goto("http://localhost:1437/voices/new?fixture=desktop&inspectors=1&auditionForm=1&voiceAudition=1&locale=en&theme=dark");
  await page.getByRole("article").filter({ hasText: "山风候选" }).getByRole("button", { name: "Open audition settings" }).click();
  const englishDialog = page.getByRole("dialog", { name: "Open audition settings" });
  const englishText = englishDialog.getByRole("textbox", { name: "Audition text" });
  await englishText.fill("");
  await englishDialog.getByRole("button", { name: "Generate audition" }).click();
  await englishDialog.getByText("Enter audition text.").waitFor();
  assert.equal(await englishText.evaluate((element) => element === document.activeElement), true);
  console.log("PASS audition form validation, target draft, explicit submit and route recovery");
} catch (error) { console.error((await page.locator("body").innerText()).slice(0, 2500)); console.error(await page.evaluate(() => window.fixture?.unexpected)); throw error; } finally { await browser.close(); }
});
