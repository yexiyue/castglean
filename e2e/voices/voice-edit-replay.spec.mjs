import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("voice-edit-replay", async ({ flowBrowser: browser }) => {
const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
page.setDefaultTimeout(15000);
try {
  await page.goto("http://localhost:1437/voices?fixture=desktop&manyVoices=1&library=mine");
  const open = async name => { await page.getByRole("button", { name: `查看音色「${name}」` }).click(); await page.getByRole("button", { name: "管理音色", exact: true }).click(); };
  await open("山风");
  await page.evaluate(() => { window.fixture.loseVoiceReply = true; });
  await page.getByRole("textbox", { name: "音色名称" }).fill("第一次名称");
  await page.getByRole("button", { name: "保存名称" }).click();
  await page.getByText("上次音色修改的结果尚未确认。重试会使用原操作身份。").waitFor();
  await page.evaluate(() => window.fixture.changeVoiceName("fixture-voice", "后来的人工名称"));
  await page.keyboard.press("Escape"); await page.keyboard.press("Escape");
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "模型中心", exact: true }).click();
  await page.getByRole("navigation", { name: "应用导航" }).getByRole("link", { name: "音色中心", exact: true }).click();
  await page.getByRole("tab", { name: "我的音色" }).click();
  await page.getByRole("button", { name: "查看音色，在管理音色中核对" }).click();
  await page.getByRole("button", { name: "管理音色", exact: true }).click();
  await page.getByRole("button", { name: "重试原音色修改" }).click();
  await open("后来的人工名称");
  assert.equal(await page.getByRole("textbox", { name: "音色名称" }).inputValue(), "后来的人工名称");
  const calls = await page.evaluate(() => ({ calls: window.fixture.calls.filter(c => c.command === "rename_library_voice"), writes: window.fixture.voiceEditWrites }));
  assert.equal(calls.calls.length, 2); assert.deepEqual(calls.calls[0].args, calls.calls[1].args); assert.equal(calls.writes, 1);
  await page.evaluate(() => { window.fixture.failVoiceReadAfterWrite = true; });
  await page.getByRole("textbox", { name: "声音描述" }).fill("已保存描述");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.getByText("音色修改已确认，待读取当前音色。", { exact: true }).waitFor();
  const before = await page.evaluate(() => window.fixture.calls.filter(c => c.command === "describe_library_voice").length);
  await page.evaluate(() => { window.fixture.failVoiceRead = false; });
  await page.getByRole("button", { name: "重新读取已保存音色" }).click();
  await open("后来的人工名称");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "已保存描述");
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === "describe_library_voice").length), before);
  await page.evaluate(() => { window.fixture.loseVoiceReply = true; });
  await page.getByRole("textbox", { name: "声音描述" }).fill("丢失回执的描述");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.getByText("上次音色修改的结果尚未确认。重试会使用原操作身份。").waitFor();
  await page.evaluate(() => window.fixture.changeVoiceDescription("fixture-voice", "后来的人工描述"));
  const beforeReplay = await page.evaluate(() => window.fixture.voiceEditWrites);
  await page.getByRole("button", { name: "重试原音色修改" }).click();
  await open("后来的人工名称");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "后来的人工描述");
  const replay = await page.evaluate(() => ({ calls: window.fixture.calls.filter(c => c.command === "describe_library_voice").slice(-2), writes: window.fixture.voiceEditWrites }));
  assert.deepEqual(replay.calls[0].args, replay.calls[1].args);
  assert.equal(replay.writes, beforeReplay);
  await page.evaluate(() => { window.fixture.failVoiceEdit = true; });
  await page.getByRole("textbox", { name: "声音描述" }).fill("失败的描述草稿");
  await page.getByRole("button", { name: "保存描述" }).click();
  await page.getByText("上次音色修改的结果尚未确认。重试会使用原操作身份。").waitFor();
  await page.evaluate(() => { window.fixture.failVoiceEdit = false; });
  await page.getByRole("button", { name: "重试原音色修改" }).click();
  await page.getByText("原操作仍未确认，请重试或读取当前值后决定如何处理。").waitFor();
  assert.equal(await page.evaluate(() => window.fixture.voiceEditWrites), beforeReplay);
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "失败的描述草稿");
  await page.getByRole("button", { name: "读取当前音色" }).click();
  await page.getByRole("button", { name: "采用当前值并放弃本次修改" }).click();
  await open("后来的人工名称");
  assert.equal(await page.getByRole("textbox", { name: "声音描述" }).inputValue(), "后来的人工描述");
  console.log("PASS voice edit replay preserves later edits and confirmed writes are only read again");
} finally { await browser.close(); }
});
