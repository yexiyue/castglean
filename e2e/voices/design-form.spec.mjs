import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("design-form", async ({ flowBrowser: browser }) => {
const page = await browser.newPage();
page.setDefaultTimeout(20000);
try {
  await page.goto("http://localhost:1437/voices/new?fixture=desktop&voiceAudition=1");
  const name = page.getByLabel("音色名称");
  const description = page.getByLabel("声音描述");
  await page.getByRole("button", { name: "生成音色候选" }).click();
  await page.getByText("请输入名称，最多 256 字节。").waitFor();
  assert.equal(await name.evaluate((element) => element === document.activeElement), true);
  await name.fill("测".repeat(86));
  await page.getByRole("button", { name: "生成音色候选" }).click();
  await page.getByText("请输入名称，最多 256 字节。").waitFor();
  await name.fill("山风");
  await page.getByRole("button", { name: "生成音色候选" }).click();
  await page.getByText("请输入符合引擎限制的声音描述。").waitFor();
  assert.equal(await description.evaluate((element) => element === document.activeElement), true);
  await description.fill("柔和的声音");
  await page.getByRole("button", { name: "高级选项" }).click();
  const seed = page.getByLabel("随机种子（可选）");
  await seed.fill("4294967296");
  assert.equal(await seed.getAttribute("aria-invalid"), "true");
  await page.getByText("随机种子请输入 0 到 4294967295 之间的整数。", { exact: true }).first().waitFor();
  await seed.fill("0");
  assert.equal(await seed.getAttribute("aria-invalid"), "false");
  await page.keyboard.press("Escape");
  await page.getByRole("tab", { name: "参考录音" }).click();
  await page.getByRole("button", { name: "选择参考 WAV" }).click();
  await page.getByText("请输入准确转写，最多 16384 字节。").waitFor();
  assert.equal(await page.getByLabel("准确转写").evaluate((element) => element === document.activeElement), true);
  await page.getByLabel("准确转写").fill("公开参考文字");
  await page.getByRole("tab", { name: "文字设计" }).click();
  assert.equal(await description.inputValue(), "柔和的声音");
  await page.locator('[data-slot="page-heading"]').getByRole("link", { name: "音色中心" }).click();
  await page.getByRole("link", { name: "创建音色", exact: true }).click();
  assert.equal(await page.getByLabel("声音描述").inputValue(), "柔和的声音");
  await page.getByRole("tab", { name: "参考录音" }).click();
  assert.equal(await page.getByLabel("准确转写").inputValue(), "公开参考文字");
  assert.equal(await page.evaluate(() => window.fixture.calls.filter(call => ["start_voice_job", "select_voice_reference"].includes(call.command)).length), 0);
  await page.getByRole("tab", { name: "文字设计" }).click();
  await page.getByRole("button", { name: "生成音色候选" }).click();
  await page.waitForFunction(() => window.fixture.calls.some(call => call.command === "start_voice_job"));
  const request = await page.evaluate(() => window.fixture.calls.find(call => call.command === "start_voice_job").args.request);
  assert.equal(request.kind, "design");
  assert.equal(request.name, "山风");
  assert.equal(request.description, "柔和的声音");
  assert.equal(request.seed, 0);
  await page.waitForFunction(() => [...document.querySelectorAll("button")].some(button => button.textContent.includes("生成音色候选") && !button.disabled));
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), true);
  await page.getByRole("button", { name: "重置创建草稿" }).click();
  assert.equal(await page.getByLabel("音色名称").inputValue(), "");
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), false);
  console.log("PASS creation validation, focus and mode drafts");
} finally { await browser.close(); }
});
