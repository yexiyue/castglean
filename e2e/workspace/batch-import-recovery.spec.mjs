import assert from 'node:assert/strict';
import { test } from "../managed-browser.mjs";

test("batch-import-recovery", async ({ flowBrowser: browser }) => {
const page = await browser.newPage(); page.setDefaultTimeout(15000);
try {
 await page.goto('http://localhost:1437/new?fixture=desktop&empty=1');
 await page.evaluate(() => {
   window.fixture.selectedFiles = ['first', 'second'].map(id => ({id,filename:`${id}.txt`,encoding:'utf-8',bytes:100,samples:['公开样本']}));
   window.fixture.failImportSelection = 'second';
 });
 await page.getByRole('button',{name:'选择 TXT 文件',exact:true}).click();
 await page.getByRole('button',{name:'导入并开始制作',exact:true}).click();
 await page.getByRole('alert').first().waitFor();
 assert.equal(await page.getByText('second.txt',{exact:true}).isVisible(), true);
 assert.equal(await page.getByText('first.txt',{exact:true}).count(), 0);
 await page.getByRole('button',{name:'返回章节',exact:true}).click();
 await page.waitForURL('**/project/created-project**');
 await page.getByRole('button',{name:'章节更多操作',exact:true}).click();
 await page.getByRole('menuitem',{name:'追加原文文件',exact:true}).click();
 assert.equal(await page.getByText('second.txt',{exact:true}).isVisible(), true);
 assert.equal(await page.evaluate(()=>window.fixture.calls.filter(c=>c.command==='local_source_release').length),0);
 await page.evaluate(() => { window.fixture.failImportSelection = null; });
 await page.getByRole('button',{name:'导入并开始制作',exact:true}).click();
 await page.waitForURL('**/project/created-project**');
 const imports = await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'local_project_import').map(c=>c.args.request.selectionId));
 assert.deepEqual(imports, ['first','second','second']);
 assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'local_project_create').length),1);
 await page.goto('http://localhost:1437/new?fixture=desktop&empty=1');
 await page.evaluate(() => {
   window.fixture.selectedFiles = ['first', 'second'].map(id => ({id,filename:`${id}.txt`,encoding:'utf-8',bytes:100,samples:['公开样本']}));
   window.fixture.loseImportReceipt = 'second';
   window.fixture.loseImportError = 'write_failed';
 });
 await page.getByRole('button',{name:'选择 TXT 文件',exact:true}).click();
 await page.getByRole('button',{name:'导入并开始制作',exact:true}).click();
 await page.getByText('请重试以确认上次导入结果；确认前不能更改编码或移除文件。').waitFor();
 assert.equal(await page.getByRole('button',{name:'移除 second.txt'}).isDisabled(), true);
 await page.getByRole('button',{name:'返回章节',exact:true}).click();
 await page.waitForURL('**/project/created-project**');
 await page.getByRole('button',{name:'章节更多操作',exact:true}).click();
 await page.getByRole('menuitem',{name:'追加原文文件',exact:true}).click();
 await page.getByRole('button',{name:'导入并开始制作',exact:true}).click();
 await page.waitForURL('**/project/created-project**');
 const retries = await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'local_project_import' && c.args.request.selectionId === 'second').map(c => c.args.request));
 assert.equal(retries.length, 2);
 assert.deepEqual(retries[1], retries[0]);
 await page.goto('http://localhost:1437/new?fixture=desktop&empty=1');
 await page.evaluate(() => {
   window.fixture.selectedFiles = ['first', 'second'].map(id => ({id,filename:`${id}.txt`,encoding:'utf-8',bytes:100,samples:['公开样本']}));
   window.fixture.failImportSelection = 'second';
   window.fixture.failImportCode = 'conflict';
 });
 await page.getByRole('button',{name:'选择 TXT 文件',exact:true}).click();
 await page.getByRole('button',{name:'导入并开始制作',exact:true}).click();
 await page.getByRole('button',{name:'重新读取工程',exact:true}).waitFor();
 await page.evaluate(() => { window.fixture.failImportSelection = null; window.fixture.advanceImportRevision(); });
 await page.getByRole('button',{name:'重新读取工程',exact:true}).click();
 await page.getByRole('button',{name:'导入并开始制作',exact:true}).click();
 await page.waitForURL('**/project/created-project**');
 const conflicts = await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'local_project_import' && c.args.request.selectionId === 'second').map(c => c.args.request));
 assert.equal(conflicts[1].revision, conflicts[0].revision + 1);
 assert.notEqual(conflicts[1].commandId, conflicts[0].commandId);
 await page.goto('http://localhost:1437/new?fixture=desktop&empty=1&persistImport=1');
 await page.evaluate(() => {
   window.fixture.selectedFiles = ['first', 'duplicate'].map(id => ({id,filename:`${id}.txt`,encoding:'utf-8',bytes:100,samples:['公开样本']}));
   window.fixture.failImportSelection = 'duplicate';
   window.fixture.failImportCode = 'duplicate_source';
 });
 await page.getByRole('button',{name:'选择 TXT 文件',exact:true}).click();
 assert.equal(await page.getByRole('combobox',{name:'duplicate.txt 的 TXT 字符编码'}).isVisible(), true);
 await page.getByRole('combobox',{name:'duplicate.txt 的 TXT 字符编码'}).selectOption('gbk');
 await page.evaluate(() => { window.fixture.failPreviewSelection = 'first'; });
 await page.getByRole('combobox',{name:'first.txt 的 TXT 字符编码'}).selectOption('gb18030');
 await page.getByText('无法按所选编码读取，请选择其他编码。').first().waitFor();
 assert.equal(await page.getByRole('combobox',{name:'first.txt 的 TXT 字符编码'}).inputValue(), 'utf-8');
 assert.equal(await page.getByRole('combobox',{name:'duplicate.txt 的 TXT 字符编码'}).inputValue(), 'gbk');
 await page.getByRole('button',{name:'导入并开始制作',exact:true}).click();
 await page.getByText('正文已导入，请移除此文件。').first().waitFor();
 await page.getByRole('button',{name:'移除 duplicate.txt'}).click();
 assert.equal(await page.getByText('duplicate.txt',{exact:true}).count(), 0);
 await page.getByRole('button',{name:'返回章节',exact:true}).click();
 await page.waitForURL('**/project/created-project**');
 assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'local_project_import' && c.args.request.selectionId === 'first').length), 1);
 await page.evaluate(() => history.replaceState(null, '', '/project/created-project?fixture=desktop&persistImport=1'));
 await page.reload();
 await page.getByRole('button',{name:'章节更多操作',exact:true}).waitFor();
 assert.equal(new URL(page.url()).pathname, '/project/created-project');
 assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'local_project_import').length), 0);
 await page.goto('http://localhost:1437/new?fixture=desktop&empty=1');
 await page.evaluate(() => { window.fixture.selectedFiles = [{id:'abandoned',filename:'abandoned.txt',encoding:'utf-8',bytes:100,samples:['公开样本']}]; });
 await page.getByRole('button',{name:'选择 TXT 文件',exact:true}).click();
 await page.getByText('abandoned.txt',{exact:true}).waitFor();
 let unloadPrompt = false;
 page.once('dialog', async dialog => { unloadPrompt = dialog.type() === 'beforeunload'; await dialog.accept(); });
 await page.reload();
 await page.waitForFunction(() => window.fixture.calls.some(c => c.command === 'local_source_release' && c.args.selectionId === 'abandoned'));
 assert.equal(unloadPrompt, true);
 assert.equal(await page.evaluate(() => sessionStorage.getItem('castglean.pending-source-selections')), null);
 await page.evaluate(() => sessionStorage.setItem('castglean.pending-source-selections', JSON.stringify(['stale'])));
 await page.goto('http://localhost:1437/new?fixture=desktop&empty=1&failRelease=1');
 await page.waitForFunction(() => window.fixture.calls.some(c => c.command === 'local_source_release'));
 await page.getByRole('button',{name:'选择 TXT 文件',exact:true}).click();
 await page.getByRole('alert').first().waitFor();
 assert.equal(await page.evaluate(() => window.fixture.calls.some(c => c.command === 'local_source_select')), false);
 await page.evaluate(() => { window.fixture.failRelease = false; window.fixture.selectionResult = 'file'; });
 await page.getByRole('button',{name:'选择 TXT 文件',exact:true}).click();
 await page.getByText('公开样本.txt',{exact:true}).waitFor();
 assert.equal(await page.evaluate(() => window.fixture.calls.filter(c => c.command === 'local_source_release').length), 3);
 console.log('PASS batch import retains failed source and retries without duplicating committed sources');
} finally { await browser.close(); }
});
