import assert from "node:assert/strict";
import { test } from "../managed-browser.mjs";

test("project-assistant-send-failure", async ({ flowBrowser: browser }) => {
const page = await browser.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto("http://localhost:1437/project/fixture-project?fixture=desktop&analysis=1&windowFixture=1");
  await page.getByRole("button", { name: "返回 AI 助手", exact: true }).click();
  const input = page.getByRole("textbox", { name: "工程问题或补充说明" });
  await input.fill("公开故障测试");
  await page.evaluate(() => { window.fixture.failAiStart = true; });
  const send = page.getByRole("button", { name: "发送", exact: true });
  const starts = () => page.evaluate(() => window.fixture.calls.filter(call => call.command === "ai_start").length);
  await send.click();
  await page.getByText("助手请求未完成，已有结果保留；请在助手中查看并选择后续操作。").waitFor();
  assert.equal(await input.inputValue(), "公开故障测试");
  assert.equal(await starts(), 1);
  assert.equal(await page.evaluate(() => { const event = new Event("beforeunload", { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; }), true);
  await page.waitForFunction(() => typeof window.fixture.fireWindowClose === "function");
  await page.evaluate(() => window.fixture.fireWindowClose());
  await page.getByText("助手请求尚未核对；关闭后本次请求身份会丢失，无法继续按原身份恢复。").waitFor();
  await page.getByRole("button", { name: "继续使用" }).click();
  await page.getByRole("button", { name: "关闭工程标签：山海之间" }).click();
  await page.waitForURL(url => url.pathname === "/");
  await page.locator('a[href*="/project/fixture-project"]').first().click();
  await page.getByRole("button", { name: "核对原请求" }).waitFor();
  assert.equal(await input.inputValue(), "公开故障测试");
  assert.equal(await starts(), 1);
  await page.getByRole("button", { name: "制作结果", exact: true }).click();
  await page.locator('[aria-label="工程首页"]').click();
  await page.locator('nav[aria-label="已打开的工程"] a[href*="fixture-project"]').click();
  await page.getByRole("button", { name: "返回章节制作", exact: true }).click();
  await page.getByRole("button", { name: "核对原请求" }).waitFor();
  await page.evaluate(() => { window.fixture.failAiStart = false; });
  await page.waitForTimeout(300);
  assert.equal(await starts(), 1);
  assert.equal(await send.isDisabled(), true);
  await page.getByRole("button", { name: "核对原请求" }).click();
  await page.getByRole("button", { name: "重试原请求" }).click();
  await page.waitForFunction(() => window.fixture.calls.filter(call => call.command === "ai_start").length === 2);
  assert.equal(await page.evaluate(() => { const calls = window.fixture.calls.filter(call => call.command === "ai_start"); return calls[0].args.request.requestId === calls[1].args.request.requestId; }), true);
  await page.getByText("原请求已恢复。输入和引用仍保留，请检查后再发送，避免重复提交。").waitFor();
  assert.equal(await input.inputValue(), "公开故障测试");
  assert.equal(await send.isDisabled(), true);
  await page.getByRole("button", { name: "制作结果", exact: true }).click();
  await page.locator('[aria-label="工程首页"]').click();
  await page.locator('nav[aria-label="已打开的工程"] a[href*="fixture-project"]').click();
  await page.getByRole("button", { name: "返回章节制作", exact: true }).click();
  await page.getByText("原请求已恢复。输入和引用仍保留，请检查后再发送，避免重复提交。").waitFor();
  await page.getByRole("button", { name: "我已了解" }).click();
  await page.getByRole("button", { name: "我已了解" }).waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "新建会话", exact: true }).click();
  await input.fill("停止恢复测试");
  await page.evaluate(() => { window.fixture.failAiStart = true; });
  await send.click();
  await page.getByRole("button", { name: "核对原请求" }).click();
  await page.getByText("当前未找到该请求；停止核对不会撤销可能已启动的任务。").waitFor();
  const beforeStop = await starts();
  await page.getByRole("button", { name: "再次核对后停止恢复" }).click();
  await page.getByText("已停止核对。原任务仍可能启动；输入和引用保留，请检查后再发送。").waitFor();
  assert.equal(await starts(), beforeStop);
  assert.equal(await input.inputValue(), "停止恢复测试");
  assert.deepEqual(errors, []);
  console.log("PASS failed project assistant send retains draft, reports failure and requires explicit retry");
} finally { await browser.close(); }
});
